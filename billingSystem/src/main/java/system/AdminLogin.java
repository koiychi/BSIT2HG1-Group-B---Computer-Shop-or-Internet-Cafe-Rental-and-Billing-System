    private void appLoginMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_appLoginMouseClicked

             try {
                      java.awt.EventQueue.invokeLater(new Runnable() {
                               @Override
                               public void run() {
                                        try {
                                                 String loginUsername = username.getText();
                                                 String loginPassword = password.getText();
                                                 if (loginUsername.equals(DatabaseManager.getAdminUsername()) && loginPassword.equals(DatabaseManager.getAdminPassword())) {
                                                          AdminAppWindow adminWindow = new AdminAppWindow();
                                                          adminWindow.setVisible(true);
                                                          AdminLogin.this.dispose();
                                                 } else {
                                                          JOptionPane.showMessageDialog(
                                                                  null, 
                                                                  "Invalid Admin Credentials", 
                                                                  "Login Error", 
                                                                  JOptionPane.ERROR_MESSAGE
                                                          );
                                                          username.setText("");
                                                          password.setText("");
                                                 }
                                        }catch (Throwable t) {
                                                 t.printStackTrace();
                                                 javax.swing.JOptionPane.showMessageDialog(null,
                                                         "Error on AdminAppWindow: " + t.getMessage(),
                                                         "Initialization Error",
                                                         javax.swing.JOptionPane.ERROR_MESSAGE);
                                        }
                               }
                      });
             } catch (Exception ex) {
                      ex.printStackTrace();
             }
    }//GEN-LAST:event_appLoginMouseClicked


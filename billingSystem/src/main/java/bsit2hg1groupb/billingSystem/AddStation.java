    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        
        String stationID = jTextField1.getText().trim();
        String stationType = jComboBox1.getSelectedItem().toString();
        String rateText = jTextField2.getText().trim();
        String status = jComboBox2.getSelectedItem().toString();
        if (stationID.isEmpty() || rateText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please fill in Station ID and Hourly Rate."
            );
            return;
        }

        try {
            double hourlyRate = Double.parseDouble(rateText);

            if (hourlyRate <= 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Hourly rate must be greater than zero."
                );
                return;
            }

            boolean available = status.equalsIgnoreCase("Available");
            Station station;

            if (stationType.equals("Gaming")) {
                station = new GamingStation(
                        stationID,
                        hourlyRate,
                        true,
                        available,
                        new java.util.ArrayList<String>()
                );
            } else {
                station = new RegularStation(
                        stationID,
                        hourlyRate,
                        true,
                        available,
                        new java.util.ArrayList<String>(),
                        false
                );
            }

            if (onStationSaved == null) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "The main window is not connected to Save yet."
                );
                return;
            }

            onStationSaved.accept(station);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Station " + stationID + " saved successfully!"
            );

            dispose();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter a valid number for Hourly Rate."
            );
        }

    }//GEN-LAST:event_jButton2ActionPerformed


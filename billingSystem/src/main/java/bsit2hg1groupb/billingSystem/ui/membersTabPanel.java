    private void editMember(int row) {
        String username = membersTableModel.getValueAt(row, 0).toString();
        JTextField nameField = new JTextField(membersTableModel.getValueAt(row, 1).toString());
        JTextField balanceField = new JTextField(membersTableModel.getValueAt(row, 2).toString());
        String currentDiscount = membersTableModel.getValueAt(row, 3).toString().replace("%", "");
        JTextField discountField = new JTextField(currentDiscount);

        JPanel form = new JPanel(new java.awt.GridLayout(3, 2, 8, 10));
        form.add(new JLabel("Full Name:"));
        form.add(nameField);
        form.add(new JLabel("Credit Balance:"));
        form.add(balanceField);
        form.add(new JLabel("Discount Rate (%):"));
        form.add(discountField);

        Object[] options = {"Save Changes", "Delete Member", "Cancel"};

        int result = JOptionPane.showOptionDialog(
                this,
                form,
                "Edit Member: " + username,
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.PLAIN_MESSAGE,
                null,
                options,
                options[0]
        );

        if (result == 0) {
            String name = nameField.getText().trim();
            if (name.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Name cannot be empty.", "Invalid Input", JOptionPane.WARNING_MESSAGE);
                return;
            }

            try {
                double balance = Double.parseDouble(balanceField.getText());
                double discount = Double.parseDouble(discountField.getText());

                if (!Double.isFinite(balance) || !Double.isFinite(discount)
                        || balance < 0 || discount < 0 || discount > 100) {
                    throw new NumberFormatException();
                }

                membersTableModel.setValueAt(name, row, 1);
                membersTableModel.setValueAt(String.format(java.util.Locale.US, "%.2f", balance), row, 2);
                membersTableModel.setValueAt(String.format(java.util.Locale.US, "%.2f%%", discount), row, 3);

            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Enter a valid balance and a discount from 0 to 100.", "Invalid Input", JOptionPane.ERROR_MESSAGE);
            }

        } else if (result == 1) {
            int confirm = JOptionPane.showConfirmDialog(
                    this,
                    "Delete member " + username + "?",
                    "Confirm Delete",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE
            );
            if (confirm == JOptionPane.YES_OPTION) {
                membersTableModel.removeRow(row);
                memberPasswords.remove(username);
            }
        }
    }


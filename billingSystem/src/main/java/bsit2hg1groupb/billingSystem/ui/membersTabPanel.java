        addDialogLabel(form, "Customer Name", 25, 62, 250, 24, 17, true);
        addDialogLabel(form, "Last Name", 25, 90, 150, 16, 11, false);
        addDialogLabel(form, "Given Name", 215, 90, 150, 16, 11, false);
        lastNameField.setBounds(25, 108, 180, 30);

    private void refreshStationCards() {
        MidPanel.removeAll();
        MidPanel.setLayout(new BorderLayout());

        JPanel cardsPanel = new JPanel(new GridLayout(0, 4, 10, 10));
        cardsPanel.setBorder(
                BorderFactory.createEmptyBorder(15, 15, 15, 15)
        );

        for (Station station : stations) {
            JPanel card = new JPanel();
            card.setLayout(new BoxLayout(card, BoxLayout.Y_AXIS));
            
            switch (station.getStatus()) {
                case "Available":
                    card.setBackground(new Color(198, 239, 206)); // Green
                    break;

                case "In Use":
                    card.setBackground(new Color(255, 199, 206)); // Red
                    break;

                case "Maintenance":
                    card.setBackground(new Color(255, 235, 156)); // Yellow
                    break;
            }
            card.setLayout(new BoxLayout(card, BoxLayout.Y_AXIS));
            card.setBorder(
                    BorderFactory.createCompoundBorder(
                            BorderFactory.createLineBorder(Color.LIGHT_GRAY),
                            BorderFactory.createEmptyBorder(8, 8, 8, 8)
                    )
            );
            card.setPreferredSize(new Dimension(150, 110));
           

            card.add(new JLabel("Station ID: " + station.getStationID()));
            card.add(new JLabel("Type: " + station.getClass().getSimpleName()));
            card.add(new JLabel("Hourly Rate: " + station.getHourlyRate()));
            card.add(new JLabel("Status: " + station.getStatus()));

            cardsPanel.add(card);
        }

        JScrollPane scrollPane = new JScrollPane(cardsPanel);
        MidPanel.add(scrollPane, BorderLayout.CENTER);

        MidPanel.revalidate();
        MidPanel.repaint();
}

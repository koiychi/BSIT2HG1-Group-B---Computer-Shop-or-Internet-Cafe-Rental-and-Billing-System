    // Custom Button Editor para sa Action column
    private class MemberButtonEditor extends javax.swing.AbstractCellEditor implements javax.swing.table.TableCellEditor {

        private final JButton button;
        private int selectedModelRow;

        public MemberButtonEditor() {
            button = new JButton("✎ Edit Member");
            button.setForeground(Color.WHITE);
            button.setBackground(new Color(35, 35, 39));
            button.setFocusPainted(false);

            button.addActionListener(e -> {
                int row = selectedModelRow;
                fireEditingStopped();
                if (row >= 0 && row < membersTableModel.getRowCount()) {
                    editMember(row);
                }
            });
        }

        @Override
        public java.awt.Component getTableCellEditorComponent(JTable table, Object value, boolean isSelected, int row, int column) {
            selectedModelRow = table.convertRowIndexToModel(row);
            return button;
        }

        @Override
        public Object getCellEditorValue() {
            return "Edit Member";
        }
    }

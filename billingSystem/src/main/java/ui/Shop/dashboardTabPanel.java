         private void updateShopState(boolean open) {
                  if (!javax.swing.SwingUtilities.isEventDispatchThread()) {
                           javax.swing.SwingUtilities.invokeLater(() -> updateShopState(open));
                           return;
                  }

                  CardLayout layout = (CardLayout) activeSessionsMainPanel.getLayout();
                  layout.show(activeSessionsMainPanel, open ? "shopIsOpen" : "shopIsClosed");
                  newSessionButton.setEnabled(open);
                  CloseShopBtn.setText(open ? "Close Shop" : "Open Shop");
                  CloseShopBtn1.setText(open ? "Close Shop" : "Open Shop");
                  String iconPath = open
                           ? "/icons/door_front_30dp_FFFFFF_FILL0_wght400_GRAD0_opsz24.png"
                           : "/icons/door_open_18dp_E3E3E3_FILL0_wght400_GRAD0_opsz20.png";
                  CloseShopBtn.setIcon(new javax.swing.ImageIcon(getClass().getResource(iconPath)));
                  CloseShopBtn1.setIcon(new javax.swing.ImageIcon(getClass().getResource(iconPath)));
                  revalidate();
                  repaint();
         }


